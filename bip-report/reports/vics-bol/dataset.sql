-- ============================================================================
-- VICS Bill of Lading dataset: the most recent loaded trailer for one facility.
--
-- Two kinds of rows, like the heatmap:
--   ROW_TYPE = ORDER      one per customer PO   (Customer Order Information)
--   ROW_TYPE = COMMODITY  one per tire category (Carrier Information)
-- Every row also carries the BOL header fields and grand totals, so the template
-- can print them outside any loop.
--
-- Pallets per line = ceiling(qty / tires per pallet); weight = tires + 40 lb per pallet.
-- NMFC # and class are LTL-only fields on the VICS form, blank for a full trailer.
-- ============================================================================
WITH SHIP AS (
    SELECT s.*
    FROM WMS.SHIPMENT s
    JOIN WMS.WAREHOUSE w ON w.WAREHOUSE_ID = s.WAREHOUSE_ID
    WHERE w.WAREHOUSE_CODE = :P_FACILITY
      AND s.SHIPMENT_STATUS IN ('LOADED', 'SHIPPED')
    ORDER BY s.SHIP_DATE DESC, s.SHIPMENT_ID DESC
    FETCH FIRST 1 ROW ONLY
),
BARCODE AS (
    -- Code 128 (set B) text for the Libre Barcode 128 font: start B + data + check + stop.
    -- Check value = (104 + sum of position * (ASCII - 32)) mod 103. U& literals keep the
    -- non-ASCII start/stop/check characters valid in the UTF-8 database.
    SELECT BOL_NUMBER, PRO_NUMBER,
           MOD(104
             + CASE WHEN LENGTH(BOL_NUMBER) >= 1 THEN 1 * (ASCII(SUBSTR(BOL_NUMBER, 1, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 2 THEN 2 * (ASCII(SUBSTR(BOL_NUMBER, 2, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 3 THEN 3 * (ASCII(SUBSTR(BOL_NUMBER, 3, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 4 THEN 4 * (ASCII(SUBSTR(BOL_NUMBER, 4, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 5 THEN 5 * (ASCII(SUBSTR(BOL_NUMBER, 5, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 6 THEN 6 * (ASCII(SUBSTR(BOL_NUMBER, 6, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 7 THEN 7 * (ASCII(SUBSTR(BOL_NUMBER, 7, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 8 THEN 8 * (ASCII(SUBSTR(BOL_NUMBER, 8, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 9 THEN 9 * (ASCII(SUBSTR(BOL_NUMBER, 9, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 10 THEN 10 * (ASCII(SUBSTR(BOL_NUMBER, 10, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 11 THEN 11 * (ASCII(SUBSTR(BOL_NUMBER, 11, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 12 THEN 12 * (ASCII(SUBSTR(BOL_NUMBER, 12, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 13 THEN 13 * (ASCII(SUBSTR(BOL_NUMBER, 13, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 14 THEN 14 * (ASCII(SUBSTR(BOL_NUMBER, 14, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 15 THEN 15 * (ASCII(SUBSTR(BOL_NUMBER, 15, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 16 THEN 16 * (ASCII(SUBSTR(BOL_NUMBER, 16, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(BOL_NUMBER) >= 17 THEN 17 * (ASCII(SUBSTR(BOL_NUMBER, 17, 1)) - 32) ELSE 0 END, 103) AS BOL_CHECK,
           MOD(104
             + CASE WHEN LENGTH(PRO_NUMBER) >= 1 THEN 1 * (ASCII(SUBSTR(PRO_NUMBER, 1, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 2 THEN 2 * (ASCII(SUBSTR(PRO_NUMBER, 2, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 3 THEN 3 * (ASCII(SUBSTR(PRO_NUMBER, 3, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 4 THEN 4 * (ASCII(SUBSTR(PRO_NUMBER, 4, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 5 THEN 5 * (ASCII(SUBSTR(PRO_NUMBER, 5, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 6 THEN 6 * (ASCII(SUBSTR(PRO_NUMBER, 6, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 7 THEN 7 * (ASCII(SUBSTR(PRO_NUMBER, 7, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 8 THEN 8 * (ASCII(SUBSTR(PRO_NUMBER, 8, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 9 THEN 9 * (ASCII(SUBSTR(PRO_NUMBER, 9, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 10 THEN 10 * (ASCII(SUBSTR(PRO_NUMBER, 10, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 11 THEN 11 * (ASCII(SUBSTR(PRO_NUMBER, 11, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 12 THEN 12 * (ASCII(SUBSTR(PRO_NUMBER, 12, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 13 THEN 13 * (ASCII(SUBSTR(PRO_NUMBER, 13, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 14 THEN 14 * (ASCII(SUBSTR(PRO_NUMBER, 14, 1)) - 32) ELSE 0 END
             + CASE WHEN LENGTH(PRO_NUMBER) >= 15 THEN 15 * (ASCII(SUBSTR(PRO_NUMBER, 15, 1)) - 32) ELSE 0 END, 103) AS PRO_CHECK
    FROM SHIP
),
LINES AS (
    SELECT o.ORDER_ID, o.ORDER_NUMBER, o.CUSTOMER_PO, l.ORDERED_QTY AS QTY,
           CEILING(DECIMAL(l.ORDERED_QTY) / i.UNITS_PER_PALLET) AS PALLETS,
           l.ORDERED_QTY * i.UNIT_WEIGHT_LBS + CEILING(DECIMAL(l.ORDERED_QTY) / i.UNITS_PER_PALLET) * 40 AS WEIGHT,
           CASE WHEN i.DESCRIPTION LIKE '%All Terrain%' THEN 2 ELSE 1 END AS CATEGORY
    FROM SHIP s
    JOIN WMS.OUTBOUND_ORDER o ON o.SHIPMENT_ID = s.SHIPMENT_ID
    JOIN WMS.OUTBOUND_LINE l ON l.ORDER_ID = o.ORDER_ID
    JOIN WMS.ITEM i ON i.ITEM_ID = l.ITEM_ID
),
TOT AS (
    SELECT INTEGER(SUM(PALLETS)) AS TOTAL_PALLETS, SUM(QTY) AS TOTAL_PIECES,
           INTEGER(SUM(WEIGHT)) AS TOTAL_WEIGHT, COUNT(DISTINCT ORDER_ID) AS ORDER_COUNT
    FROM LINES
),
HDR AS (
    SELECT s.BOL_NUMBER, VARCHAR_FORMAT(s.SHIP_DATE, 'MM/DD/YYYY') AS SHIP_DATE,
           s.TRAILER_NUMBER, s.SEAL_NUMBER, s.PRO_NUMBER, s.SPECIAL_INSTRUCTIONS,
           w.WAREHOUSE_CODE, w.WAREHOUSE_NAME AS FROM_NAME, w.ADDRESS_LINE1 AS FROM_ADDRESS,
           w.CITY || ', ' || w.STATE_CODE || ' ' || w.POSTAL_CODE AS FROM_CITY_STATE_ZIP,
           w.SHIPPER_ID AS FROM_SID,
           t.SHIP_TO_NAME AS TO_NAME, t.ADDRESS_LINE1 AS TO_ADDRESS,
           t.CITY || ', ' || t.STATE_CODE || ' ' || t.POSTAL_CODE AS TO_CITY_STATE_ZIP,
           t.LOCATION_NUMBER AS TO_LOCATION, t.CUSTOMER_ID AS TO_CID,
           c.CARRIER_NAME, c.SCAC,
           U&'\00CC' || b.BOL_NUMBER || CASE WHEN b.BOL_CHECK = 0 THEN U&'\00C2' WHEN b.BOL_CHECK < 95 THEN CHR(b.BOL_CHECK + 32) ELSE SUBSTRING(U&'\00C3\00C4\00C5\00C6\00C7\00C8\00C9\00CA', b.BOL_CHECK - 94, 1, CODEUNITS32) END || U&'\00CE' AS BOL_BARCODE,
           U&'\00CC' || b.PRO_NUMBER || CASE WHEN b.PRO_CHECK = 0 THEN U&'\00C2' WHEN b.PRO_CHECK < 95 THEN CHR(b.PRO_CHECK + 32) ELSE SUBSTRING(U&'\00C3\00C4\00C5\00C6\00C7\00C8\00C9\00CA', b.PRO_CHECK - 94, 1, CODEUNITS32) END || U&'\00CE' AS PRO_BARCODE,
           CASE WHEN s.FREIGHT_TERMS = 'PREPAID' THEN '[X]' ELSE '[  ]' END AS BOX_PREPAID,
           CASE WHEN s.FREIGHT_TERMS = 'COLLECT' THEN '[X]' ELSE '[  ]' END AS BOX_COLLECT,
           CASE WHEN s.FREIGHT_TERMS = 'THIRD_PARTY' THEN '[X]' ELSE '[  ]' END AS BOX_THIRD_PARTY,
           CASE WHEN s.TRAILER_LOADED_BY = 'SHIPPER' THEN '[X]' ELSE '[  ]' END AS BOX_LOADED_SHIPPER,
           CASE WHEN s.TRAILER_LOADED_BY = 'DRIVER' THEN '[X]' ELSE '[  ]' END AS BOX_LOADED_DRIVER,
           CASE WHEN s.FREIGHT_COUNTED_BY = 'SHIPPER' THEN '[X]' ELSE '[  ]' END AS BOX_COUNTED_SHIPPER,
           CASE WHEN s.FREIGHT_COUNTED_BY = 'DRIVER_PALLETS' THEN '[X]' ELSE '[  ]' END AS BOX_COUNTED_DRV_PALLETS,
           CASE WHEN s.FREIGHT_COUNTED_BY = 'DRIVER_PIECES' THEN '[X]' ELSE '[  ]' END AS BOX_COUNTED_DRV_PIECES,
           tot.TOTAL_PALLETS, tot.TOTAL_PIECES, tot.TOTAL_WEIGHT, tot.ORDER_COUNT
    FROM SHIP s
    JOIN WMS.WAREHOUSE w ON w.WAREHOUSE_ID = s.WAREHOUSE_ID
    JOIN WMS.SHIP_TO t ON t.SHIP_TO_ID = s.SHIP_TO_ID
    JOIN WMS.CARRIER c ON c.CARRIER_CODE = s.CARRIER_CODE
    JOIN BARCODE b ON b.BOL_NUMBER = s.BOL_NUMBER
    CROSS JOIN TOT tot
),
ROWS_ AS (
    -- Customer Order Information: one row per PO
    SELECT 'ORDER' AS ROW_TYPE, 1 AS SECTION_SORT, MIN(ORDER_NUMBER) AS SORT_KEY,
           CUSTOMER_PO AS ORD_PO, MIN(ORDER_NUMBER) AS ORD_NUMBER,
           INTEGER(SUM(PALLETS)) AS ORD_PKGS, INTEGER(SUM(WEIGHT)) AS ORD_WEIGHT,
           'Y' AS ORD_PALLET_SLIP,
           'Sales order ' || MIN(ORDER_NUMBER) AS ORD_ADDL_INFO,
           CAST(NULL AS INTEGER) AS CMD_HU_QTY, CAST(NULL AS VARCHAR(8)) AS CMD_HU_TYPE,
           CAST(NULL AS INTEGER) AS CMD_PKG_QTY, CAST(NULL AS VARCHAR(8)) AS CMD_PKG_TYPE,
           CAST(NULL AS INTEGER) AS CMD_WEIGHT, CAST(NULL AS VARCHAR(2)) AS CMD_HM,
           CAST(NULL AS VARCHAR(60)) AS CMD_DESCRIPTION
    FROM LINES
    GROUP BY CUSTOMER_PO
    UNION ALL
    -- Carrier Information: one row per commodity (tire category)
    SELECT 'COMMODITY', 2, CHAR(CATEGORY),
           NULL, NULL, NULL, NULL, NULL, NULL,
           INTEGER(SUM(PALLETS)), 'PLT', SUM(QTY), 'TIRES', INTEGER(SUM(WEIGHT)), '',
           CASE CATEGORY WHEN 1 THEN 'New pneumatic tires, touring (passenger)'
                         ELSE 'New pneumatic tires, all-terrain (light truck)' END
    FROM LINES
    GROUP BY CATEGORY
)
SELECT r.ROW_TYPE, r.ORD_PO, r.ORD_NUMBER, r.ORD_PKGS, r.ORD_WEIGHT, r.ORD_PALLET_SLIP, r.ORD_ADDL_INFO,
       r.CMD_HU_QTY, r.CMD_HU_TYPE, r.CMD_PKG_QTY, r.CMD_PKG_TYPE, r.CMD_WEIGHT, r.CMD_HM, r.CMD_DESCRIPTION,
       h.*
FROM ROWS_ r CROSS JOIN HDR h
ORDER BY r.SECTION_SORT, r.SORT_KEY
WITH UR;
