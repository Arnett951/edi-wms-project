-- ============================================================================
-- Location Aging Heatmap dataset, one facility.
--
-- One row per rack row (aisle + level) with the 10 bays pivoted into columns
-- (B01_* .. B10_*), plus one row per floor area (QUALITY / RETURNS / RECEIVING).
-- Every location is listed, empty ones included.
--
-- Heat bucket per occupied location, ranked by its oldest lot's age (days since
-- received) across the whole facility:
--   RED    = oldest 10% of occupied locations  (10% of the count, rounded up;
--            ties share a color, so a bucket can run slightly over)
--   YELLOW = next 10%
--   GREEN  = the rest
--   EMPTY  = no inventory
-- The percentile ranking is done here with window functions; the RTF template only
-- maps each bucket to a cell color (BI Publisher conditional formatting).
-- ============================================================================
WITH LOC AS (
    SELECT l.LOCATION_ID, l.LOCATION_CODE, l.ZONE, l.AISLE, l.BAY, l.RACK_LEVEL,
           w.WAREHOUSE_CODE, w.WAREHOUSE_NAME
    FROM WMS.LOCATION l
    JOIN WMS.WAREHOUSE w ON w.WAREHOUSE_ID = l.WAREHOUSE_ID
    WHERE w.WAREHOUSE_CODE = :P_FACILITY
      -- the rack grid, plus the floor areas (the old floor PICK-01 / BULK-01 are retired)
      AND (l.AISLE IS NOT NULL OR l.ZONE IN ('QUALITY', 'RETURNS', 'RECEIVING'))
),
LOTS AS (
    SELECT n.LOCATION_ID, i.SKU,
           DAYS(CURRENT DATE) - DAYS(n.RECEIVED_DATE) AS AGE_DAYS,
           ROW_NUMBER() OVER (PARTITION BY n.LOCATION_ID ORDER BY n.RECEIVED_DATE, i.SKU) AS RN,
           COUNT(*) OVER (PARTITION BY n.LOCATION_ID) AS LOT_COUNT
    FROM WMS.INVENTORY n
    JOIN WMS.ITEM i ON i.ITEM_ID = n.ITEM_ID
    WHERE n.ON_HAND_QTY > 0
),
CELL AS (   -- one row per location: its oldest lot (if any)
    SELECT loc.*, o.SKU, o.AGE_DAYS, o.LOT_COUNT
    FROM LOC loc
    LEFT JOIN LOTS o ON o.LOCATION_ID = loc.LOCATION_ID AND o.RN = 1
),
RANKED AS (
    SELECT c.*,
           CASE WHEN c.AGE_DAYS IS NULL THEN NULL
                -- RANK, not ROW_NUMBER: locations with the same age share a rank, so ties
                -- always get the same color (a bucket can run slightly over 10% on ties).
                ELSE RANK() OVER (PARTITION BY CASE WHEN c.AGE_DAYS IS NULL THEN 0 ELSE 1 END
                                  ORDER BY c.AGE_DAYS DESC) END AS AGE_RANK,
           COUNT(c.AGE_DAYS) OVER () AS OCCUPIED
    FROM CELL c
),
HEATED AS (
    SELECT r.*,
           CASE WHEN r.AGE_DAYS IS NULL THEN 'EMPTY'
                WHEN r.AGE_RANK <= CEILING(r.OCCUPIED * 0.10) THEN 'RED'
                WHEN r.AGE_RANK <= 2 * CEILING(r.OCCUPIED * 0.10) THEN 'YELLOW'
                ELSE 'GREEN' END AS HEAT
    FROM RANKED r
),
SUMMARY AS (
    SELECT MAX(WAREHOUSE_CODE) AS WAREHOUSE_CODE, MAX(WAREHOUSE_NAME) AS WAREHOUSE_NAME,
           COUNT(*) AS TOTAL_LOCS, MAX(OCCUPIED) AS OCCUPIED_LOCS,
           SUM(CASE WHEN HEAT = 'RED' THEN 1 ELSE 0 END) AS RED_LOCS,
           SUM(CASE WHEN HEAT = 'YELLOW' THEN 1 ELSE 0 END) AS YELLOW_LOCS,
           SUM(CASE WHEN HEAT = 'GREEN' THEN 1 ELSE 0 END) AS GREEN_LOCS,
           MIN(CASE WHEN HEAT = 'RED' THEN AGE_DAYS END) AS RED_MIN_AGE,
           MIN(CASE WHEN HEAT = 'YELLOW' THEN AGE_DAYS END) AS YELLOW_MIN_AGE,
           MAX(AGE_DAYS) AS MAX_AGE,
           VARCHAR_FORMAT(CURRENT DATE, 'YYYY-MM-DD') AS REPORT_DATE
    FROM HEATED
)
SELECT 'RACK' AS ROW_TYPE, 1 AS SECTION_SORT, c.AISLE, c.RACK_LEVEL,
       CAST(NULL AS VARCHAR(20)) AS AREA_LOC, CAST(NULL AS VARCHAR(12)) AS AREA_ZONE,
       CAST(NULL AS VARCHAR(20)) AS AREA_SKU, CAST(NULL AS INTEGER) AS AREA_AGE,
       CAST(NULL AS INTEGER) AS AREA_LOTS, CAST(NULL AS VARCHAR(20)) AS AREA_HEAT,
       MAX(CASE WHEN c.BAY = 1 THEN c.LOCATION_CODE END) AS B01_LOC,
       MAX(CASE WHEN c.BAY = 1 THEN c.SKU END) AS B01_SKU,
       MAX(CASE WHEN c.BAY = 1 THEN c.AGE_DAYS END) AS B01_AGE,
       MAX(CASE WHEN c.BAY = 1 THEN c.LOT_COUNT END) AS B01_LOTS,
       MAX(CASE WHEN c.BAY = 1 THEN c.HEAT END) AS B01_HEAT,
       MAX(CASE WHEN c.BAY = 2 THEN c.LOCATION_CODE END) AS B02_LOC,
       MAX(CASE WHEN c.BAY = 2 THEN c.SKU END) AS B02_SKU,
       MAX(CASE WHEN c.BAY = 2 THEN c.AGE_DAYS END) AS B02_AGE,
       MAX(CASE WHEN c.BAY = 2 THEN c.LOT_COUNT END) AS B02_LOTS,
       MAX(CASE WHEN c.BAY = 2 THEN c.HEAT END) AS B02_HEAT,
       MAX(CASE WHEN c.BAY = 3 THEN c.LOCATION_CODE END) AS B03_LOC,
       MAX(CASE WHEN c.BAY = 3 THEN c.SKU END) AS B03_SKU,
       MAX(CASE WHEN c.BAY = 3 THEN c.AGE_DAYS END) AS B03_AGE,
       MAX(CASE WHEN c.BAY = 3 THEN c.LOT_COUNT END) AS B03_LOTS,
       MAX(CASE WHEN c.BAY = 3 THEN c.HEAT END) AS B03_HEAT,
       MAX(CASE WHEN c.BAY = 4 THEN c.LOCATION_CODE END) AS B04_LOC,
       MAX(CASE WHEN c.BAY = 4 THEN c.SKU END) AS B04_SKU,
       MAX(CASE WHEN c.BAY = 4 THEN c.AGE_DAYS END) AS B04_AGE,
       MAX(CASE WHEN c.BAY = 4 THEN c.LOT_COUNT END) AS B04_LOTS,
       MAX(CASE WHEN c.BAY = 4 THEN c.HEAT END) AS B04_HEAT,
       MAX(CASE WHEN c.BAY = 5 THEN c.LOCATION_CODE END) AS B05_LOC,
       MAX(CASE WHEN c.BAY = 5 THEN c.SKU END) AS B05_SKU,
       MAX(CASE WHEN c.BAY = 5 THEN c.AGE_DAYS END) AS B05_AGE,
       MAX(CASE WHEN c.BAY = 5 THEN c.LOT_COUNT END) AS B05_LOTS,
       MAX(CASE WHEN c.BAY = 5 THEN c.HEAT END) AS B05_HEAT,
       MAX(CASE WHEN c.BAY = 6 THEN c.LOCATION_CODE END) AS B06_LOC,
       MAX(CASE WHEN c.BAY = 6 THEN c.SKU END) AS B06_SKU,
       MAX(CASE WHEN c.BAY = 6 THEN c.AGE_DAYS END) AS B06_AGE,
       MAX(CASE WHEN c.BAY = 6 THEN c.LOT_COUNT END) AS B06_LOTS,
       MAX(CASE WHEN c.BAY = 6 THEN c.HEAT END) AS B06_HEAT,
       MAX(CASE WHEN c.BAY = 7 THEN c.LOCATION_CODE END) AS B07_LOC,
       MAX(CASE WHEN c.BAY = 7 THEN c.SKU END) AS B07_SKU,
       MAX(CASE WHEN c.BAY = 7 THEN c.AGE_DAYS END) AS B07_AGE,
       MAX(CASE WHEN c.BAY = 7 THEN c.LOT_COUNT END) AS B07_LOTS,
       MAX(CASE WHEN c.BAY = 7 THEN c.HEAT END) AS B07_HEAT,
       MAX(CASE WHEN c.BAY = 8 THEN c.LOCATION_CODE END) AS B08_LOC,
       MAX(CASE WHEN c.BAY = 8 THEN c.SKU END) AS B08_SKU,
       MAX(CASE WHEN c.BAY = 8 THEN c.AGE_DAYS END) AS B08_AGE,
       MAX(CASE WHEN c.BAY = 8 THEN c.LOT_COUNT END) AS B08_LOTS,
       MAX(CASE WHEN c.BAY = 8 THEN c.HEAT END) AS B08_HEAT,
       MAX(CASE WHEN c.BAY = 9 THEN c.LOCATION_CODE END) AS B09_LOC,
       MAX(CASE WHEN c.BAY = 9 THEN c.SKU END) AS B09_SKU,
       MAX(CASE WHEN c.BAY = 9 THEN c.AGE_DAYS END) AS B09_AGE,
       MAX(CASE WHEN c.BAY = 9 THEN c.LOT_COUNT END) AS B09_LOTS,
       MAX(CASE WHEN c.BAY = 9 THEN c.HEAT END) AS B09_HEAT,
       MAX(CASE WHEN c.BAY = 10 THEN c.LOCATION_CODE END) AS B10_LOC,
       MAX(CASE WHEN c.BAY = 10 THEN c.SKU END) AS B10_SKU,
       MAX(CASE WHEN c.BAY = 10 THEN c.AGE_DAYS END) AS B10_AGE,
       MAX(CASE WHEN c.BAY = 10 THEN c.LOT_COUNT END) AS B10_LOTS,
       MAX(CASE WHEN c.BAY = 10 THEN c.HEAT END) AS B10_HEAT,
       s.*
FROM HEATED c CROSS JOIN SUMMARY s
WHERE c.AISLE IS NOT NULL
GROUP BY c.AISLE, c.RACK_LEVEL, s.WAREHOUSE_CODE, s.WAREHOUSE_NAME, s.TOTAL_LOCS, s.OCCUPIED_LOCS,
         s.RED_LOCS, s.YELLOW_LOCS, s.GREEN_LOCS, s.RED_MIN_AGE, s.YELLOW_MIN_AGE, s.MAX_AGE, s.REPORT_DATE
UNION ALL
SELECT 'AREA', 2, CAST(NULL AS VARCHAR(4)), CAST(NULL AS SMALLINT),
       c.LOCATION_CODE, c.ZONE, c.SKU, c.AGE_DAYS, c.LOT_COUNT, c.HEAT,
       CAST(NULL AS VARCHAR(20)) AS B01_LOC,
       CAST(NULL AS VARCHAR(20)) AS B01_SKU,
       CAST(NULL AS INTEGER) AS B01_AGE,
       CAST(NULL AS INTEGER) AS B01_LOTS,
       CAST(NULL AS VARCHAR(20)) AS B01_HEAT,
       CAST(NULL AS VARCHAR(20)) AS B02_LOC,
       CAST(NULL AS VARCHAR(20)) AS B02_SKU,
       CAST(NULL AS INTEGER) AS B02_AGE,
       CAST(NULL AS INTEGER) AS B02_LOTS,
       CAST(NULL AS VARCHAR(20)) AS B02_HEAT,
       CAST(NULL AS VARCHAR(20)) AS B03_LOC,
       CAST(NULL AS VARCHAR(20)) AS B03_SKU,
       CAST(NULL AS INTEGER) AS B03_AGE,
       CAST(NULL AS INTEGER) AS B03_LOTS,
       CAST(NULL AS VARCHAR(20)) AS B03_HEAT,
       CAST(NULL AS VARCHAR(20)) AS B04_LOC,
       CAST(NULL AS VARCHAR(20)) AS B04_SKU,
       CAST(NULL AS INTEGER) AS B04_AGE,
       CAST(NULL AS INTEGER) AS B04_LOTS,
       CAST(NULL AS VARCHAR(20)) AS B04_HEAT,
       CAST(NULL AS VARCHAR(20)) AS B05_LOC,
       CAST(NULL AS VARCHAR(20)) AS B05_SKU,
       CAST(NULL AS INTEGER) AS B05_AGE,
       CAST(NULL AS INTEGER) AS B05_LOTS,
       CAST(NULL AS VARCHAR(20)) AS B05_HEAT,
       CAST(NULL AS VARCHAR(20)) AS B06_LOC,
       CAST(NULL AS VARCHAR(20)) AS B06_SKU,
       CAST(NULL AS INTEGER) AS B06_AGE,
       CAST(NULL AS INTEGER) AS B06_LOTS,
       CAST(NULL AS VARCHAR(20)) AS B06_HEAT,
       CAST(NULL AS VARCHAR(20)) AS B07_LOC,
       CAST(NULL AS VARCHAR(20)) AS B07_SKU,
       CAST(NULL AS INTEGER) AS B07_AGE,
       CAST(NULL AS INTEGER) AS B07_LOTS,
       CAST(NULL AS VARCHAR(20)) AS B07_HEAT,
       CAST(NULL AS VARCHAR(20)) AS B08_LOC,
       CAST(NULL AS VARCHAR(20)) AS B08_SKU,
       CAST(NULL AS INTEGER) AS B08_AGE,
       CAST(NULL AS INTEGER) AS B08_LOTS,
       CAST(NULL AS VARCHAR(20)) AS B08_HEAT,
       CAST(NULL AS VARCHAR(20)) AS B09_LOC,
       CAST(NULL AS VARCHAR(20)) AS B09_SKU,
       CAST(NULL AS INTEGER) AS B09_AGE,
       CAST(NULL AS INTEGER) AS B09_LOTS,
       CAST(NULL AS VARCHAR(20)) AS B09_HEAT,
       CAST(NULL AS VARCHAR(20)) AS B10_LOC,
       CAST(NULL AS VARCHAR(20)) AS B10_SKU,
       CAST(NULL AS INTEGER) AS B10_AGE,
       CAST(NULL AS INTEGER) AS B10_LOTS,
       CAST(NULL AS VARCHAR(20)) AS B10_HEAT,
       s.*
FROM HEATED c CROSS JOIN SUMMARY s
WHERE c.AISLE IS NULL
-- rack rows: aisle A..D, top level first (like looking at the rack face); then floor areas
ORDER BY 2, 3, 4 DESC, 5
