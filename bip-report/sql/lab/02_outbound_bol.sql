-- Lines in full-pallet quantities (40 touring or 24 all-terrain tires per pallet).
INSERT INTO WMS.OUTBOUND_LINE (ORDER_ID, LINE_NUMBER, ITEM_ID, ORDERED_QTY, PICKED_QTY, SHIPPED_QTY)
WITH L (ORDER_NUMBER, LINE_NUMBER, SKU, QTY) AS (VALUES
    ('DEMO-SO-1001', 1, 'TIRE-001', 160), ('DEMO-SO-1001', 2, 'TIRE-002', 120),
    ('DEMO-SO-1002', 1, 'TIRE-003', 120), ('DEMO-SO-1002', 2, 'TIRE-005', 72),
