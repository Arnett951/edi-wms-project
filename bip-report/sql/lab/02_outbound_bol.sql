COMMIT;

-- Checks: per trailer, orders / pallets / tires / weight (tires + 40 lb per pallet).
SELECT s.BOL_NUMBER, w.WAREHOUSE_CODE, COUNT(DISTINCT o.ORDER_ID) AS ORDERS,
       SUM(CEILING(DECIMAL(l.ORDERED_QTY) / i.UNITS_PER_PALLET)) AS PALLETS,
       SUM(l.ORDERED_QTY) AS TIRES,
       SUM(l.ORDERED_QTY * i.UNIT_WEIGHT_LBS + CEILING(DECIMAL(l.ORDERED_QTY) / i.UNITS_PER_PALLET) * 40) AS WEIGHT_LBS
FROM WMS.SHIPMENT s
JOIN WMS.WAREHOUSE w ON w.WAREHOUSE_ID = s.WAREHOUSE_ID
JOIN WMS.OUTBOUND_ORDER o ON o.SHIPMENT_ID = s.SHIPMENT_ID
JOIN WMS.OUTBOUND_LINE l ON l.ORDER_ID = o.ORDER_ID
JOIN WMS.ITEM i ON i.ITEM_ID = l.ITEM_ID
GROUP BY s.BOL_NUMBER, w.WAREHOUSE_CODE;

CONNECT RESET;
