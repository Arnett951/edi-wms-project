SELECT o.ORDER_ID, L.LINE_NUMBER, i.ITEM_ID, L.QTY, L.QTY, 0
FROM L JOIN WMS.OUTBOUND_ORDER o ON o.ORDER_NUMBER = L.ORDER_NUMBER
       JOIN WMS.ITEM i ON i.SKU = L.SKU;

GRANT SELECT ON WMS.CARRIER TO USER RPTVIEW;
GRANT SELECT ON WMS.SHIP_TO TO USER RPTVIEW;
