        WHEN 'TIRE-005' THEN 30 WHEN 'TIRE-006' THEN 40 WHEN 'TIRE-007' THEN 45 WHEN 'TIRE-008' THEN 24 END,
    UNITS_PER_PALLET = CASE WHEN DESCRIPTION LIKE '%All Terrain%' THEN 24 ELSE 40 END;

