-- ============================================================================
-- Outbound shipment data for the VICS Bill of Lading report (Db2 LUW lab, synthetic).
--
--  * Ship-from addresses on WMS.WAREHOUSE; unit weight and tires-per-pallet on WMS.ITEM.
--  * New WMS.CARRIER, WMS.SHIP_TO and WMS.SHIPMENT (one row per trailer / BOL).
--  * OUTBOUND_ORDER gets SHIPMENT_ID and CUSTOMER_PO.
--  * One loaded trailer per facility: three customer POs for one Hello World Tire
--    store, ~21 pallets. The trailer (SHIPMENT) is LOADED; its orders stay PICKING
--    (fully picked, not yet shipped), since the lab schema limits ORDER_STATUS to
--    RELEASED / PICKING / HOLD / SHIPPED. The BOL is printed at this point, before the
--    driver signs and the orders move to SHIPPED.
--
-- BOL numbers use the VICS 17-digit format: GS1 company prefix + serial + GS1 mod-10
-- check digit. 0614141 is GS1s documentation example prefix, not a real companys.
-- All names, addresses, SCAC, trailer, seal and PRO numbers are fictional.
--
-- Backups first (BAK20260925.*_B2). Run once, all-or-nothing:
--   db2 +c -s -tf 02_outbound_bol.sql
-- ============================================================================

