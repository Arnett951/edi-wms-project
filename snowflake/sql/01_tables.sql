-- =====================================================
-- WMS lab tables in Snowflake (WMSLAB.RAW), column for column with Azure SQL
-- wmslab.* (powerbi/sql/01_wmslab_tables.sql), plus the stage and file format
-- the copy script loads through. Idempotent; copy_azuresql_to_snowflake.py
-- runs it before every load.
-- Snowflake records but does not enforce PRIMARY KEY; the reconcile step in
-- the copy script is what actually catches duplicates.
-- =====================================================
CREATE SCHEMA IF NOT EXISTS WMSLAB.RAW;
CREATE SCHEMA IF NOT EXISTS WMSLAB.ANALYTICS;

CREATE TABLE IF NOT EXISTS WMSLAB.RAW.WAREHOUSE (
    WAREHOUSE_ID   NUMBER(10,0) NOT NULL PRIMARY KEY,
    WAREHOUSE_CODE VARCHAR(12)  NOT NULL,
    WAREHOUSE_NAME VARCHAR(80)  NOT NULL,
    ADDRESS_LINE1  VARCHAR(60),
    CITY           VARCHAR(40),
    STATE_CODE     CHAR(2),
    POSTAL_CODE    VARCHAR(10),
    SHIPPER_ID     VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS WMSLAB.RAW.ITEM (
    ITEM_ID          NUMBER(10,0)  NOT NULL PRIMARY KEY,
    SKU              VARCHAR(24)   NOT NULL,
    DESCRIPTION      VARCHAR(100)  NOT NULL,
    TIRE_SIZE        VARCHAR(24)   NOT NULL,
    UNIT_COST        NUMBER(12,2)  NOT NULL,
    UNIT_WEIGHT_LBS  NUMBER(6,2),
    UNITS_PER_PALLET NUMBER(5,0)
);

CREATE TABLE IF NOT EXISTS WMSLAB.RAW.LOCATION (
    LOCATION_ID   NUMBER(10,0) NOT NULL PRIMARY KEY,
    WAREHOUSE_ID  NUMBER(10,0) NOT NULL,
    LOCATION_CODE VARCHAR(20)  NOT NULL,
    ZONE          VARCHAR(12)  NOT NULL,
    AISLE         VARCHAR(4),
    BAY           NUMBER(5,0),
    RACK_LEVEL    NUMBER(5,0)
);

CREATE TABLE IF NOT EXISTS WMSLAB.RAW.INVENTORY (
    INVENTORY_ID  NUMBER(10,0) NOT NULL PRIMARY KEY,
    LOCATION_ID   NUMBER(10,0) NOT NULL,
    ITEM_ID       NUMBER(10,0) NOT NULL,
    LOT_NUMBER    VARCHAR(24)  NOT NULL,
    RECEIVED_DATE DATE         NOT NULL,
    STOCK_STATUS  VARCHAR(12)  NOT NULL,
    ON_HAND_QTY   NUMBER(10,0) NOT NULL,
    RESERVED_QTY  NUMBER(10,0) NOT NULL
);

CREATE TABLE IF NOT EXISTS WMSLAB.RAW.LOT_ATTRIBUTE (
    LOT_NUMBER VARCHAR(24)  NOT NULL,
    ITEM_ID    NUMBER(10,0) NOT NULL,
    DOT_CODE   VARCHAR(40)  NOT NULL,
    MFG_WEEK   NUMBER(5,0)  NOT NULL,
    MFG_YEAR   NUMBER(5,0)  NOT NULL,
    MFG_DATE   DATE         NOT NULL,
    PRIMARY KEY (ITEM_ID, LOT_NUMBER)
);

-- One row per copy run, with the reconcile result.
CREATE TABLE IF NOT EXISTS WMSLAB.RAW.LOAD_LOG (
    LOAD_ID     NUMBER AUTOINCREMENT PRIMARY KEY,
    LOADED_AT   TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    SOURCE      VARCHAR(80)  NOT NULL,
    ROW_COUNTS  VARCHAR(400) NOT NULL,
    RECONCILED  BOOLEAN      NOT NULL
);

CREATE FILE FORMAT IF NOT EXISTS WMSLAB.RAW.WMS_CSV
    TYPE = CSV
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    SKIP_HEADER = 1
    NULL_IF = ('')
    EMPTY_FIELD_AS_NULL = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

CREATE STAGE IF NOT EXISTS WMSLAB.RAW.LOAD_STAGE
    FILE_FORMAT = WMSLAB.RAW.WMS_CSV
    COMMENT = 'CSV extracts from Azure SQL wmslab, one folder per table';

-- Same rows and columns as wmslab.vw_InventoryAging (T-SQL) and the BIP
-- inventory-aging dataset (Db2), translated to Snowflake SQL.
CREATE OR REPLACE VIEW WMSLAB.ANALYTICS.VW_INVENTORY_AGING AS
SELECT w.WAREHOUSE_CODE, w.WAREHOUSE_NAME, i.SKU, i.DESCRIPTION, i.TIRE_SIZE,
       l.LOCATION_CODE, l.ZONE, inv.LOT_NUMBER,
       la.DOT_CODE, la.MFG_WEEK, la.MFG_YEAR, la.MFG_DATE, inv.RECEIVED_DATE,
       MIN(inv.RECEIVED_DATE) OVER (PARTITION BY w.WAREHOUSE_CODE, i.SKU) AS OLDEST_RECEIVED_DATE,
       DATEDIFF(day, inv.RECEIVED_DATE, CURRENT_DATE()) AS WAREHOUSE_AGE_DAYS,
       DATEDIFF(day, la.MFG_DATE, CURRENT_DATE()) AS TIRE_AGE_DAYS,
       inv.STOCK_STATUS, inv.ON_HAND_QTY, inv.RESERVED_QTY,
       IFF(inv.STOCK_STATUS = 'AVAILABLE', inv.ON_HAND_QTY - inv.RESERVED_QTY, 0) AS AVAILABLE_QTY,
       CAST(inv.ON_HAND_QTY * i.UNIT_COST AS NUMBER(14,2)) AS INVENTORY_VALUE
FROM WMSLAB.RAW.INVENTORY inv
JOIN WMSLAB.RAW.ITEM i ON i.ITEM_ID = inv.ITEM_ID
JOIN WMSLAB.RAW.LOCATION l ON l.LOCATION_ID = inv.LOCATION_ID
JOIN WMSLAB.RAW.WAREHOUSE w ON w.WAREHOUSE_ID = l.WAREHOUSE_ID
LEFT JOIN WMSLAB.RAW.LOT_ATTRIBUTE la ON la.ITEM_ID = inv.ITEM_ID AND la.LOT_NUMBER = inv.LOT_NUMBER
WHERE DATEDIFF(day, inv.RECEIVED_DATE, CURRENT_DATE()) >= 7;
